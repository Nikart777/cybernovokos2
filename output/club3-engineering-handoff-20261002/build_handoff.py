def table(headers,rows,widths=None):
    t=doc.add_table(rows=1,cols=len(headers))
    t.autofit=False
    for i,v in enumerate(headers): t.rows[0].cells[i].text=str(v)
    rep=OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(rep)
    for row in rows:
        cells=t.add_row().cells
        for i,v in enumerate(row): cells[i].text=str(v)
    for ri,row in enumerate(t.rows):
        no_split=OxmlElement('w:cantSplit'); row._tr.get_or_add_trPr().append(no_split)
        for ci,cell in enumerate(row.cells):
            if widths: cell.width=Cm(widths[ci])
            tcpr=cell._tc.get_or_add_tcPr()
            if ri==0:
                shade=OxmlElement('w:shd'); shade.set(qn('w:fill'),'EDEDED'); tcpr.append(shade)
            for pp in cell.paragraphs:
                pp.paragraph_format.space_after=Pt(4)
                pp.paragraph_format.space_before=Pt(3)
                for run in pp.runs:
                    run.font.size=Pt(9)
                    run.font.bold=(ri==0)
    borders=OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        el=OxmlElement('w:'+edge); el.set(qn('w:val'),'single'); el.set(qn('w:sz'),'4'); el.set(qn('w:color'),'CCCCCC'); borders.append(el)
    t._tbl.tblPr.append(borders)
    lines.append(' | '.join(headers))
    for row in rows: lines.append(' | '.join(map(str,row)))
    lines.append('')
    doc.add_paragraph().paragraph_format.space_after=Pt(0)
    return t

def link(label,url):
    if doc.paragraphs:
        doc.paragraphs[-1].paragraph_format.keep_with_next=True
    pp=doc.add_paragraph()
    pp.paragraph_format.space_after=Pt(3)
    rel=pp.part.relate_to(url,'http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink',is_external=True)
    hyper=OxmlElement('w:hyperlink'); hyper.set(qn('r:id'),rel)
    run=OxmlElement('w:r'); props=OxmlElement('w:rPr')
    col=OxmlElement('w:color'); col.set(qn('w:val'),'24546B'); props.append(col)
    size=OxmlElement('w:sz'); size.set(qn('w:val'),'18'); props.append(size)
    run.append(props); tx=OxmlElement('w:t'); tx.text=label; run.append(tx); hyper.append(run); pp._p.append(hyper)
    lines.append(f'{label}: {url}')

